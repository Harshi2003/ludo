// Plays a 4-bot Fog City game and screenshots the board, a world-event banner and the finish.
import puppeteer from "puppeteer-core";
const out = process.argv[2] ?? ".";
const url = process.env.URL ?? "http://localhost:3000";
const browser = await puppeteer.launch({ executablePath: "C:/Program Files/Google/Chrome/Application/chrome.exe", headless: "new", args: ["--use-angle=d3d11", "--ignore-gpu-blocklist"] });
const page = await browser.newPage();
const errors = [];
page.on("pageerror", (e) => errors.push(e.message));
page.on("console", (m) => m.type() === "error" && errors.push(m.text()));
await page.setViewport({ width: 1440, height: 900 });
await page.goto(url, { waitUntil: "networkidle0" });
await page.evaluate(() => localStorage.setItem("ludo:world", "fog-city"));
await page.screenshot({ path: `${out}/sf-home.png` });
await page.goto(`${url}/?watch=4&seed=11&human=none`, { waitUntil: "networkidle0" });
await new Promise((r) => setTimeout(r, 2500));
await page.screenshot({ path: `${out}/sf-board.png` });
await page.click('button[aria-label="Overview"]');
await new Promise((r) => setTimeout(r, 1200));
await page.screenshot({ path: `${out}/sf-overview.png` });
await page.click('button[aria-label="Follow"]');
await page.click('button[aria-label="Fast bots"]');
await page.waitForFunction(() => window.__ludo?.state().events.some((e) => e.kind === "world_event"), { timeout: 300000, polling: 100 });
await new Promise((r) => setTimeout(r, 700));
await page.screenshot({ path: `${out}/sf-event.png` });
await page.waitForFunction(() => [...document.querySelectorAll(".glass")].some((d) => /^Live|:$/.test(d.firstElementChild?.textContent ?? "")), { timeout: 60000, polling: 200 }).catch(() => console.log("no narrator line seen"));
await page.click('button[aria-label="AI commentary"]');
await new Promise((r) => setTimeout(r, 400));
await page.screenshot({ path: `${out}/sf-ai.png` });
await page.click('button[aria-label="AI commentary"]');
await page.waitForFunction(() => window.__ludo?.state().phase === "over", { timeout: 600000, polling: 1000 });
await new Promise((r) => setTimeout(r, 3000));
await page.screenshot({ path: `${out}/sf-victory.png` });
const s = await page.evaluate(() => {
  const s = window.__ludo.state();
  const count = (k) => s.events.filter((e) => e.kind === k).length;
  return { round: s.round, winner: s.winner, captures: count("capture"), worldEvents: s.events.filter((e) => e.kind === "world_event").map((e) => e.source), mimics: s.events.filter((e) => e.msg.includes("copies")).length };
});
console.log(JSON.stringify(s));
console.log(errors.length ? `ERRORS:\n${errors.join("\n")}` : "no browser errors");
await browser.close();
